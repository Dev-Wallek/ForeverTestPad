"""Write TestData.lua from the in-game test list.

Reads TP_TESTS (default: tests/tests.md): each "## " section's
numbered lines are tests, the section's other lines before them its preparation,
and the bullets of the "Kampf" section the combat notes of the tests they name.
The tests next-tests.md (beside tests.md) lists come first, in its order.

Usage: python3 tools/tests_to_lua.py
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TESTS = Path(os.environ.get("TP_TESTS", ROOT / "tests" / "tests.md"))
OUT = ROOT / "TestData.lua"
COMBAT = "Kampf"


def lua(text):
    """A Lua string of Markdown text, without its code backticks (the game shows them as they are)."""
    return '"' + text.replace("`", "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def numbers(text):
    """The test numbers in "86–88", "34, 60 + Kampf", "4 / 52 / 53"."""
    found = []
    for a, b in re.findall(r"(\d+)(?:\s*[–-]\s*(\d+))?", text):
        found.extend(range(int(a), int(b or a) + 1))
    return found


def parse(text):
    tests, combat = [], {}
    section, prep, phase = None, [], ""
    for line in text.splitlines():
        if line.startswith("## "):
            section, prep, phase = line[3:].strip(), [], ""
            continue
        if section is None or not line.strip():
            continue
        if section == COMBAT:
            bullet = re.match(r"- ([\d /]+): (.+)", line)
            if bullet:
                for n in numbers(bullet.group(1)):
                    combat.setdefault(n, []).append((phase + ": " if phase else "") + bullet.group(2))
            elif not line.startswith("- "):
                phase = line.strip().rstrip(":")
            continue
        test = re.match(r"(\d+)\. (.+)", line)
        if test:
            tests.append({"id": int(test.group(1)), "section": section, "prep": " ".join(prep),
                          "text": test.group(2)})
        elif not tests or tests[-1]["section"] != section:
            prep.append(line.strip())
    for t in tests:
        t["combat"] = combat.get(t["id"], [])
    return tests


def order(tests):
    nxt = TESTS.with_name("next-tests.md")
    first = []
    if nxt.exists():
        for row in nxt.read_text(encoding="utf-8").splitlines():
            cells = [c.strip() for c in row.split("|")]
            if len(cells) > 3 and cells[1].isdigit():
                first.extend(n for n in numbers(cells[2]) if n not in first)
    rank = {n: i for i, n in enumerate(first)}
    return sorted(tests, key=lambda t: (rank.get(t["id"], len(rank)), tests.index(t)))


def main():
    tests = order(parse(TESTS.read_text(encoding="utf-8")))
    out = ["-- GENERATED by tools/tests_to_lua.py from the in-game test list; don't edit.",
           "local _, TP = ...", "TP.TESTS = {"]
    for t in tests:
        combat = ", ".join(lua(c) for c in t["combat"])
        out.append(f'    {{ id = {t["id"]}, section = {lua(t["section"])}, prep = {lua(t["prep"])},')
        out.append(f'      text = {lua(t["text"])}, combat = {{ {combat} }} }},')
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(tests)} tests -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
